const PIXEL_GLYPH_W = 5;
const PIXEL_GLYPH_H = 7;
const PIXEL_GLYPH_SPACING = 1;
const GLYPH_ADVANCE = PIXEL_GLYPH_W + PIXEL_GLYPH_SPACING;

function measurePixelText(text) {
  if (!text || text.length === 0) return 0;
  return text.length * GLYPH_ADVANCE - PIXEL_GLYPH_SPACING;
}

function drawPixelGlyph(ctx, char, x, y, color) {
  const glyph = PIXEL_FONT_GLYPHS[char] || PIXEL_FONT_GLYPHS['?'];

  ctx.fillStyle = color;
  for (let row = 0; row < PIXEL_GLYPH_H; row++) {
    const line = glyph[row];
    for (let col = 0; col < PIXEL_GLYPH_W; col++) {
      if (line[col] === '#') {
        ctx.fillRect(x + col, y + row, 1, 1);
      }
    }
  }
}

function drawPixelText(ctx, text, x, y, color) {
  if (!text) return 0;
  let cx = x;
  for (let i = 0; i < text.length; i++) {
    drawPixelGlyph(ctx, text[i], cx, y, color);
    cx += GLYPH_ADVANCE;
  }
  return cx - x;
}